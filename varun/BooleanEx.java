class BooleanEx{
    public static void main(String[] args) {

        // initialize 
        boolean a = true;
        boolean b = false;
        boolean c = true;
        boolean d = false;
        boolean e = true;
        boolean f = false;
        boolean g = true;
        boolean h = false;
        boolean i = true;
        boolean j = false;

        
        System.out.println("Initial Values:");
        System.out.println(a);
        System.out.println(b);
        System.out.println(c);
        System.out.println(d);
        System.out.println(e);
        System.out.println(f);
        System.out.println(g);
        System.out.println(h);
        System.out.println(i);
        System.out.println(j);

        // Re-initialize 
        a = false;
        b = true;
        c = false;
        d = true;
        e = false;
        f = true;
        g = false;
        h = true;
        i = false;
        j = true;

      
        System.out.println("Re-initialized Values:");
        System.out.println(a);
        System.out.println(b);
        System.out.println(c);
        System.out.println(d);
        System.out.println(e);
        System.out.println(f);
        System.out.println(g);
        System.out.println(h);
        System.out.println(i);
        System.out.println(j);
    }
}