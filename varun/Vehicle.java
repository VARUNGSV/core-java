class Vehicle {
    public static void main(String[] args) {

        // initialize 
        long a = 100000L;
        long b = 200000L;
        long c = 300000L;
        long d = 400000L;
        long e = 500000L;

        
        System.out.println("Initial Values:");
        System.out.println(a);
        System.out.println(b);
        System.out.println(c);
        System.out.println(d);
        System.out.println(e);

        // Re-initialize
        a = 600000L;
        b = 700000L;
        c = 800000L;
        d = 900000L;
        e = 1000000L;

        
        System.out.println("Re-initialized Values:");
        System.out.println(a);
        System.out.println(b);
        System.out.println(c);
        System.out.println(d);
        System.out.println(e);
    }
}