class Temperature {
    public static void main(String[] args) {

        // initialize 
        float a = 10.5f;
        float b = 20.5f;
        float c = 30.5f;
        float d = 40.5f;
        float e = 50.5f;

  
        System.out.println("Initial Values:");
        System.out.println(a);
        System.out.println(b);
        System.out.println(c);
        System.out.println(d);
        System.out.println(e);

        // Re-initialize 
        a = 60.5f;
        b = 70.5f;
        c = 80.5f;
        d = 90.5f;
        e = 100.5f;

        System.out.println("Re-initialized Values:");
        System.out.println(a);
        System.out.println(b);
        System.out.println(c);
        System.out.println(d);
        System.out.println(e);
    }
}