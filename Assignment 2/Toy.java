class Toy {

    static void play() {
        System.out.println("Playing with the toy.");
    }

    static void move() {
        System.out.println("Moving the toy.");
    }

    static void sound() {
        System.out.println("Toy is making sound.");
    }

    static void rotate() {
        System.out.println("Rotating the toy.");
    }

    static void store() {
        System.out.println("Keeping the toy safely.");
    }

    public static void main(String[] args) {

        play();

        move();
        move();

        sound();
        sound();
        sound();

        rotate();
        rotate();
        rotate();
        rotate();

        store();
        store();
        store();
        store();
        store();
    }
}