class Cap {

    static void wear() {
        System.out.println("Wearing the cap.");
    }

    static void adjust() {
        System.out.println("Adjusting the cap.");
    }

    static void clean() {
        System.out.println("Cleaning the cap.");
    }

    static void remove() {
        System.out.println("Removing the cap.");
    }

    static void store() {
        System.out.println("Keeping the cap safely.");
    }

    public static void main(String[] args) {

        wear();

        adjust();
        adjust();

        clean();
        clean();
        clean();

        remove();
        remove();
        remove();
        remove();

        store();
        store();
        store();
        store();
        store();
    }
}